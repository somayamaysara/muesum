<script>
$(document).ready(function(){

    $(".filter-btn").click(function(){
        $(".filter-btn").removeClass("btn-gold").addClass("btn-light");
        $(this).removeClass("btn-light").addClass("btn-gold");
        let filter=$(this).text();
        
        if (filter == "الكل") {
            $(".card").show();
        }
        else if (filter == "التماثيل") {
            $(".card").hide();
            $(".statue").show();
        }
        else if (filter == "الكنوز") {
            $(".card").hide();
            $(".treasure").show();
        }
        else if (filter == "المجوهرات") {
            $(".card").hide();
            $(".jewelry").show();
        }
        else if (filter == "الفخار") {
            $(".card").hide();
            $(".pottery").show();
        }

    });
});
</script>
